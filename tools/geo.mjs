// Club coordinates for the fictional world: each fictional club sits on a real club's slot, so it takes the real town's
// coordinates (facts, free to use); the names stay fictional. Clubs in one town are spread a few streets apart.
//   node tools/geo.mjs          write js/geo.js from data/real-world.json + data/city-coords.txt
//   node tools/geo.mjs --check  fail if a club has no coordinates or js/geo.js is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const real = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/real-world.json'), 'utf8'));
const coords = {};
for (const line of fs.readFileSync(path.join(ROOT, 'data/city-coords.txt'), 'utf8').split('\n')) {
  const m = line.match(/^([A-Z]{3}):(.+) (-?[\d.]+),(-?[\d.]+)$/);
  if (m) coords[`${m[1]}:${m[2]}`] = [+m[3], +m[4]];
}
const hash = (s) => {
  let h = 2166136261;
  for (const c of String(s)) h = Math.imul(h ^ c.charCodeAt(0), 16777619);
  return h >>> 0;
};
const missing = [],
  out = {};
for (const [code, c] of Object.entries(real.clubs)) {
  const ll = coords[`${c.nat}:${c.row[2]}`];
  if (!ll) {
    missing.push(`${code} ${c.nat}:${c.row[2]}`);
    continue;
  }
  const jit = (k) => (((hash(code + k) % 1000) / 1000 - 0.5) * 0.06).toFixed(3) * 1; // ~3 km
  out[code] = [+(ll[0] + jit('a')).toFixed(2), +(ll[1] + jit('b')).toFixed(2)];
}
const body = Object.entries(out)
  .map(([k, v]) => `    ${k}: [${v[0]}, ${v[1]}],`)
  .join('\n');
const src = `// Club coordinates [latitude, longitude] by club code: the real town each fictional club sits on (generated by tools/geo.mjs
// from data/city-coords.txt; do not edit by hand).
(function () {
  const FM = window.FM;
  FM.D.CLUB_GEO = {
${body}
  };
})();
`;
const file = path.join(ROOT, 'js/geo.js');
if (process.argv.includes('--check')) {
  if (missing.length) (console.error('no coordinates:', missing.join(', ')), process.exit(1));
  if (fs.readFileSync(file, 'utf8') !== src)
    (console.error('js/geo.js is out of date: run node tools/geo.mjs'), process.exit(1));
  console.log(`geo ok: ${Object.keys(out).length} clubs`);
} else {
  if (missing.length) console.warn('no coordinates for', missing.join(', '));
  fs.writeFileSync(file, src);
  console.log(`wrote js/geo.js: ${Object.keys(out).length} clubs`);
}
