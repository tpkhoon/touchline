// Turns the Last Row sample data (19 Liverpool goals tracked by hand, 20 frames a second; Ricardo Tavares / Friends of Tracking,
// https://github.com/Friends-of-Tracking-Data-FoTD/Last-Row; no formal licence, the README says to use it for any purpose and to
// credit the source) into js/devclips.js, which the developer tools' goal replay loads. It is a reference to look at, not data
// the game learns from: the README says it lacks the accuracy needed for research (players are missing in most plays), and it
// is 19 goals. The file is only for the source folder: the developer tools and this clip file are left out of every build.
//
//   node tools/lastrow-clips.mjs --data <folder with liverpool_2019.csv>
//
// Each clip is turned to attack toward x = 1 (the goal at the right), with x and y from 0 to 1 and the ball height in metres
// as the data gives it (0 to 1.5, only filled for the ball):
//   { name, fps, goal: [x, y], frames: [ [ballX, ballY, ballZ, [id, team, x, y, id, team, x, y, ...]] ] }
// team: 1 the side that scored (the 'attack' of the data), 0 the other.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = {};
{
  const a = process.argv.slice(2);
  for (let i = 0; i < a.length; i++)
    if (a[i].startsWith('--'))
      args[a[i].slice(2)] = a[i + 1] === undefined || a[i + 1].startsWith('--') ? true : a[++i];
}
if (!args.data || args.data === true) {
  console.log('usage: node tools/lastrow-clips.mjs --data <folder with liverpool_2019.csv>');
  process.exit(1);
}
const file = path.join(path.resolve(String(args.data)), 'liverpool_2019.csv');
if (!fs.existsSync(file)) {
  console.error(`No liverpool_2019.csv in ${path.dirname(file)}`);
  process.exit(1);
}
const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/).filter(Boolean);
const head = lines[0].split(','),
  ix = Object.fromEntries(head.map((h, i) => [h, i]));
const plays = new Map();
for (const ln of lines.slice(1)) {
  const f = ln.split(',');
  const play = f[ix.play];
  if (!plays.has(play)) plays.set(play, []);
  plays
    .get(play)
    .push({
      frame: +f[ix.frame],
      player: f[ix.player],
      team: f[ix.team],
      x: +f[ix.x],
      y: +f[ix.y],
      z: f[ix.z] === '' ? 0 : +f[ix.z],
    });
}
const r1 = (v) => Math.round(v * 1000) / 1000;
const clips = [];
for (const [name, rows] of plays) {
  // the ball has no team in the data; its rows come with a height (z) and a player id of its own, so take the one track whose team is empty
  const ballRows = rows.filter((r) => r.team === ''),
    ballId = ballRows.length ? ballRows[0].player : null;
  const frames = [...new Set(rows.map((r) => r.frame))].sort((a, b) => a - b);
  const last = ballRows
    .filter((r) => r.player === ballId)
    .sort((a, b) => a.frame - b.frame)
    .pop();
  // the goal is at the end the ball finishes: turn the clip so that end is x = 1
  const flip = last && last.x < 50;
  const tx = (x) => r1((flip ? 100 - x : x) / 100),
    ty = (y) => r1((flip ? 100 - y : y) / 100);
  const byFrame = new Map(frames.map((f) => [f, { ball: null, p: [] }]));
  for (const r of rows) {
    const o = byFrame.get(r.frame);
    if (r.team === '') o.ball = [tx(r.x), ty(r.y), r1(r.z)];
    else o.p.push(r.player, r.team === 'attack' ? 1 : 0, tx(r.x), ty(r.y));
  }
  let carry = [0.5, 0.5, 0];
  const out = frames.map((f) => {
    const o = byFrame.get(f);
    if (o.ball) carry = o.ball;
    return [...carry, o.p];
  });
  clips.push({ name, fps: 20, goal: last ? [flip ? 0 : 1, 0.5] : [1, 0.5], frames: out });
}
const out = path.join(ROOT, 'js/devclips.js');
fs.writeFileSync(
  out,
  [
    '// Generated by tools/lastrow-clips.mjs from the Last Row sample data (https://github.com/Friends-of-Tracking-Data-FoTD/Last-Row): 19 Liverpool goals,',
    '// 20 frames a second, tracked by hand (Ricardo Tavares, @lastrowview). For the developer tools only: it is left out of every build.',
    '(function () {',
    `  window.FM.DEVCLIPS = ${JSON.stringify(clips)};`,
    '})();',
    '',
  ].join('\n'),
);
console.log(
  `${clips.length} clips, ${clips.reduce((a, c) => a + c.frames.length, 0)} frames, ${(fs.statSync(out).size / 1024).toFixed(0)} KB -> js/devclips.js`,
);
for (const c of clips)
  console.log(
    `  ${c.name.padEnd(34)} ${(c.frames.length / c.fps).toFixed(1)} s, ${Math.max(...c.frames.map((f) => f[3].length / 4))} tracked`,
  );
